export type StorageMethod = "冷藏" | "冷冻" | "常温";
export type FoodUnit = "克" | "个" | "盒" | "袋" | "瓶";

export interface CommonFoodItem {
  id: string;
  name: string;
  category: "主食" | "蛋白质" | "蔬菜" | "水果" | "家常菜" | "零食" | "饮品";
  defaultPortion: number; // in grams
  caloriesPer100g: number; // kcal
  proteinPer100g: number; // g
  carbsPer100g: number; // g
  fatPer100g: number; // g
  fiberPer100g: number; // g
  emoji: string;
  tags: string[];
  shelfLifeDays?: number;
  storageMethod?: StorageMethod;
  defaultUnit?: FoodUnit;
}

export function getFoodStorageDefaults(name: string, category: string, tags: string[] = []): {
  shelfLifeDays: number;
  storageMethod: StorageMethod;
  defaultUnit: FoodUnit;
} {
  const n = name.toLowerCase();
  
  // 1. 蛋奶类
  if (n.includes("鸡蛋") || n.includes("鸭蛋") || n.includes("鹌鹑蛋") || n.includes("溏心蛋")) {
    return { shelfLifeDays: 30, storageMethod: "冷藏", defaultUnit: "个" };
  }
  if (n.includes("酸奶") || n.includes("希腊酸奶")) {
    return { shelfLifeDays: 7, storageMethod: "冷藏", defaultUnit: "盒" };
  }
  if (n.includes("牛奶") || n.includes("鲜奶") || n.includes("豆浆") || n.includes("燕麦奶") || n.includes("生椰乳")) {
    return { shelfLifeDays: 7, storageMethod: "冷藏", defaultUnit: "瓶" };
  }
  if (n.includes("奶酪") || n.includes("芝士")) {
    return { shelfLifeDays: 14, storageMethod: "冷藏", defaultUnit: "袋" };
  }

  // 2. 新鲜肉类与海鲜
  if (n.includes("鸡胸") || n.includes("鸡肉") || n.includes("牛肉") || n.includes("牛排") || n.includes("猪肉") || n.includes("里脊") || n.includes("肉馅") || n.includes("排骨")) {
    return { shelfLifeDays: 2, storageMethod: "冷藏", defaultUnit: "克" };
  }
  if (n.includes("虾") || n.includes("三文鱼") || n.includes("鳕鱼") || n.includes("鲈鱼") || n.includes("金枪鱼") || n.includes("扇贝") || n.includes("蟹") || n.includes("生蚝")) {
    return { shelfLifeDays: 2, storageMethod: "冷藏", defaultUnit: "克" };
  }

  // 3. 常见蔬菜
  if (n.includes("番茄") || n.includes("西红柿")) {
    return { shelfLifeDays: 5, storageMethod: "冷藏", defaultUnit: "个" };
  }
  if (n.includes("圣女果")) {
    return { shelfLifeDays: 5, storageMethod: "冷藏", defaultUnit: "盒" };
  }
  if (n.includes("黄瓜") || n.includes("茄子") || n.includes("青椒") || n.includes("彩椒") || n.includes("西葫芦") || n.includes("苦瓜")) {
    return { shelfLifeDays: 5, storageMethod: "冷藏", defaultUnit: "个" };
  }
  if (n.includes("土豆") || n.includes("马铃薯") || n.includes("红薯") || n.includes("地瓜") || n.includes("紫薯") || n.includes("南瓜") || n.includes("山药") || n.includes("芋头") || n.includes("胡萝卜") || n.includes("白萝卜") || n.includes("洋葱") || n.includes("大蒜") || n.includes("生姜")) {
    return { shelfLifeDays: 20, storageMethod: "常温", defaultUnit: "个" };
  }
  if (n.includes("菠菜") || n.includes("生菜") || n.includes("油麦菜") || n.includes("小白菜") || n.includes("娃娃菜") || n.includes("西蓝花") || n.includes("菜花") || n.includes("芹菜") || n.includes("芦笋") || n.includes("茼蒿") || n.includes("空心菜")) {
    return { shelfLifeDays: 4, storageMethod: "冷藏", defaultUnit: "克" };
  }
  if (n.includes("豆腐") || n.includes("豆干") || n.includes("千张") || n.includes("素鸡") || n.includes("魔芋")) {
    return { shelfLifeDays: 3, storageMethod: "冷藏", defaultUnit: "盒" };
  }
  if (n.includes("菌") || n.includes("菇") || n.includes("木耳") || n.includes("金针菇") || n.includes("杏鲍菇") || n.includes("香菇")) {
    return { shelfLifeDays: 4, storageMethod: "冷藏", defaultUnit: "盒" };
  }

  // 4. 水果类
  if (n.includes("蓝莓") || n.includes("草莓") || n.includes("树莓") || n.includes("黑莓") || n.includes("车厘子") || n.includes("樱桃") || n.includes("葡萄") || n.includes("提子")) {
    return { shelfLifeDays: 4, storageMethod: "冷藏", defaultUnit: "盒" };
  }
  if (n.includes("苹果") || n.includes("梨") || n.includes("橙") || n.includes("柑") || n.includes("橘") || n.includes("柚") || n.includes("柠檬") || n.includes("西柚")) {
    return { shelfLifeDays: 15, storageMethod: "冷藏", defaultUnit: "个" };
  }
  if (n.includes("香蕉") || n.includes("牛油果") || n.includes("芒果") || n.includes("木瓜") || n.includes("猕猴桃") || n.includes("火龙果")) {
    return { shelfLifeDays: 5, storageMethod: "常温", defaultUnit: "个" };
  }

  // 5. 主食类与干货
  if (n.includes("大米") || n.includes("糙米") || n.includes("黑米") || n.includes("小米") || n.includes("燕麦") || n.includes("藜麦") || n.includes("荞麦") || n.includes("意面") || n.includes("挂面") || n.includes("面粉")) {
    return { shelfLifeDays: 365, storageMethod: "常温", defaultUnit: "袋" };
  }
  if (n.includes("吐司") || n.includes("面包") || n.includes("贝果")) {
    return { shelfLifeDays: 5, storageMethod: "常温", defaultUnit: "袋" };
  }
  if (n.includes("馒头") || n.includes("包子") || n.includes("花卷") || n.includes("饺子") || n.includes("馄饨")) {
    return { shelfLifeDays: 4, storageMethod: "冷藏", defaultUnit: "个" };
  }
  if (n.includes("米饭") || n.includes("炒饭") || n.includes("焖饭")) {
    return { shelfLifeDays: 2, storageMethod: "冷藏", defaultUnit: "克" };
  }

  // 6. 调料与饮品
  if (n.includes("油") || n.includes("醋") || n.includes("生抽") || n.includes("酱油") || n.includes("蚝油") || n.includes("黑胡椒") || n.includes("盐") || n.includes("糖") || n.includes("料酒") || n.includes("辣椒油") || n.includes("芝麻酱") || n.includes("芥末")) {
    return { shelfLifeDays: 365, storageMethod: "常温", defaultUnit: "瓶" };
  }
  if (n.includes("茶") || n.includes("咖啡") || n.includes("气泡水") || n.includes("饮料") || n.includes("果汁")) {
    return { shelfLifeDays: 180, storageMethod: "常温", defaultUnit: "瓶" };
  }
  if (n.includes("坚果") || n.includes("巴旦木") || n.includes("核桃") || n.includes("腰果") || n.includes("奇亚籽") || n.includes("花生")) {
    return { shelfLifeDays: 90, storageMethod: "常温", defaultUnit: "袋" };
  }

  // 7. 通用分类默认值
  if (category === "蔬菜") return { shelfLifeDays: 5, storageMethod: "冷藏", defaultUnit: "克" };
  if (category === "蛋白质") return { shelfLifeDays: 3, storageMethod: "冷藏", defaultUnit: "克" };
  if (category === "水果") return { shelfLifeDays: 7, storageMethod: "冷藏", defaultUnit: "个" };
  if (category === "主食") return { shelfLifeDays: 180, storageMethod: "常温", defaultUnit: "克" };
  if (category === "家常菜") return { shelfLifeDays: 2, storageMethod: "冷藏", defaultUnit: "盒" };
  if (category === "零食") return { shelfLifeDays: 90, storageMethod: "常温", defaultUnit: "袋" };
  if (category === "饮品") return { shelfLifeDays: 180, storageMethod: "常温", defaultUnit: "瓶" };

  return { shelfLifeDays: 7, storageMethod: "冷藏", defaultUnit: "克" };
}

